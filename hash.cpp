                                                                    //  Hash black king.
    for(i = ENCODE_OFFSET_BLACK_KING; i < ENCODE_OFFSET_MOVE_CTR; i++)
      {
        if(hashInputBuffer[i] < _NONE)
          {
            ull8 = zobristHashTable[ BK_A1 + hashInputBuffer[i] ];
            h ^= ull8;
          }
      }

                                                                    //  We do NOT hash the move counter.

    return h;
